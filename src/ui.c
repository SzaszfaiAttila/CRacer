/* ── Helpers ──────────────────────────────────────────────────────────────── */
static void draw_quad(UI *u,
                      float x0, float y0, float x1, float y1,
                      float tu0, float tv0, float tu1, float tv1) {
    float v[24] = {
        x0, y0,  tu0, tv0,
        x1, y0,  tu1, tv0,
        x1, y1,  tu1, tv1,
        x0, y0,  tu0, tv0,
        x1, y1,  tu1, tv1,
        x0, y1,  tu0, tv1,
    };
    glBindBuffer(GL_ARRAY_BUFFER, u->vbo);
    glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(v), v);
    glDrawArrays(GL_TRIANGLES, 0, 6);
}

static void set_proj(UI *u) {
    mat4 proj;
    glm_ortho(0.0f, u->sw, u->sh, 0.0f, -1.0f, 1.0f, proj);
    GLint loc = glGetUniformLocation(u->prog, "uProj");
    glUniformMatrix4fv(loc, 1, GL_FALSE, (float *)proj);
}

/* ── Public API ───────────────────────────────────────────────────────────── */
void ui_init(UI *u, int sw, int sh) {
    u->sw = (float)sw;
    u->sh = (float)sh;

    u->prog = shader_create("../shaders/ui_vert.glsl",
                            "../shaders/ui_frag.glsl");

    /* VAO / VBO for a single quad (6 verts × vec2 pos + vec2 uv = 24 floats) */
    glGenVertexArrays(1, &u->vao);
    glGenBuffers(1, &u->vbo);
    glBindVertexArray(u->vao);
    glBindBuffer(GL_ARRAY_BUFFER, u->vbo);
    glBufferData(GL_ARRAY_BUFFER, 24 * sizeof(float), NULL, GL_DYNAMIC_DRAW);
    /* location 0: pos (vec2) */
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void *)0);
    glEnableVertexAttribArray(0);
    /* location 1: uv  (vec2) */
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float),
                          (void *)(2 * sizeof(float)));
    glEnableVertexAttribArray(1);
    glBindVertexArray(0);

    /* ── Font texture: 1024×8 GL_R8 ──────────────────────────────────────── */
    uint8_t pixels[8][1024];
    memset(pixels, 0, sizeof(pixels));
    for (int c = 0; c < 128; c++) {
        for (int row = 0; row < 8; row++) {
            uint8_t byte = FONT[c][row];
            for (int bit = 0; bit < 8; bit++) {
                pixels[row][c * 8 + bit] = (byte & (0x80u >> bit)) ? 255u : 0u;
            }
        }
    }
    glGenTextures(1, &u->font_tex);
    glBindTexture(GL_TEXTURE_2D, u->font_tex);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8,
                 1024, 8, 0, GL_RED, GL_UNSIGNED_BYTE, pixels);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glBindTexture(GL_TEXTURE_2D, 0);
}

void ui_free(UI *u) {
    glDeleteProgram(u->prog);
    glDeleteVertexArrays(1, &u->vao);
    glDeleteBuffers(1, &u->vbo);
    glDeleteTextures(1, &u->font_tex);
}

void ui_resize(UI *u, int sw, int sh) {
    u->sw = (float)sw;
    u->sh = (float)sh;
}

void ui_begin(UI *u) {
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_CULL_FACE);   /* UI quads may face any direction */
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glDepthMask(GL_FALSE);

    glUseProgram(u->prog);
    set_proj(u);
    glBindVertexArray(u->vao);
}

void ui_end(UI *u) {
    (void)u;
    glBindVertexArray(0);
    glDepthMask(GL_TRUE);
    glDisable(GL_BLEND);
    glEnable(GL_CULL_FACE);    /* restore scene state */
    glEnable(GL_DEPTH_TEST);
}

void ui_rect(UI *u, float x, float y, float w, float h,
             float r, float g, float b, float a) {
    glUniform1i(glGetUniformLocation(u->prog, "uMode"), 0);
    glUniform4f(glGetUniformLocation(u->prog, "uColor"), r, g, b, a);
    draw_quad(u, x, y, x + w, y + h, 0, 0, 1, 1);
}

void ui_text(UI *u, const char *s, float x, float y,
             float sz, float r, float g, float b, float a) {
    glUniform1i(glGetUniformLocation(u->prog, "uMode"), 1);
    glUniform4f(glGetUniformLocation(u->prog, "uColor"), r, g, b, a);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, u->font_tex);
    glUniform1i(glGetUniformLocation(u->prog, "uFont"), 0);

    float cx = x;
    for (const char *p = s; *p; p++) {
        unsigned int c = (unsigned char)*p;
        if (c > 127) c = 63; /* '?' */
        float u0 = (float)(c * 8) / 1024.0f;
        float u1 = u0 + 8.0f / 1024.0f;
        draw_quad(u, cx, y, cx + sz, y + sz, u0, 0.0f, u1, 1.0f);
        cx += sz;
    }
    glBindTexture(GL_TEXTURE_2D, 0);
}

float ui_textw(const char *s, float sz) {
    int n = 0;
    for (const char *p = s; *p; p++) n++;
    return (float)n * sz;
}
